import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { resolve } from "node:path"
import ts from "typescript"

// Inventory the entire source tree, including currently unused registry components.
const root = fileURLToPath(new URL("../", import.meta.url))
const files = readdirSync(resolve(root, "src"), { recursive: true })
  .map(path => `src/${path.replaceAll("\\", "/")}`)
  .filter(path => /\.(tsx?|css)$/.test(path))
const palette = /\b(?:bg|text|border|ring|fill|stroke|from|via|to)-(?:red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|slate|gray|zinc|neutral|stone)-(?:\d{2,3})\b|\b(?:bg|text|border|ring|fill|stroke)-(?:white|black)\b/g
const violations = []
const rows = []
const styles = files.filter(path => path.endsWith(".css"))
const css = styles.map(path => readFileSync(resolve(root, path), "utf8")).join("\n")
const hooks = new Set([...css.matchAll(/\.([a-zA-Z_][\w-]*)/g)].map(match => match[1]))
for (const path of files.filter(path => path.endsWith(".tsx")).sort()) {
  const source = readFileSync(resolve(root, path), "utf8")
  const colors = [...source.matchAll(palette)]
  for (const match of colors) violations.push(`${path}:${source.slice(0, match.index).split("\n").length}: ${match[0]}`)
  const rawControls = [...source.matchAll(/<(?:button|input|textarea|select)\b/g)].length
  const inline = [...source.matchAll(/\bstyle=\{/g)].length
  const classTokens = new Set()
  const ast = ts.createSourceFile(path, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
  const collect = node => {
    if (ts.isStringLiteralLike(node) || ts.isTemplateHead(node) || ts.isTemplateMiddle(node) || ts.isTemplateTail(node)) {
      node.text.split(/\s+/).forEach(token => classTokens.add(token))
    }
    ts.forEachChild(node, collect)
  }
  const visit = node => {
    if (ts.isJsxAttribute(node) && node.name.getText(ast) === "className" && node.initializer) collect(node.initializer)
    else ts.forEachChild(node, visit)
  }
  visit(ast)
  const custom = [...hooks].filter(hook => classTokens.has(hook))
  rows.push(`| ${path} | ${colors.length} | ${rawControls} | ${inline} | ${custom.length ? custom.join(", ") : "—"} |`)
}
const report = [
  "# Theme source inventory", "",
  `Scanned ${files.length} TypeScript/TSX/CSS files; inventoried ${rows.length} TSX files and ${styles.length} stylesheets.`, "",
  "Generated by `node scripts/audit-theme.mjs --write`. This is a source inventory, not proof of runtime coverage. CSS hooks are matched against static className tokens; dynamically constructed classes need manual review. Native controls, inline geometry, and document styles are review candidates, not automatic violations.", "",
  "Palette utilities must use semantic theme tokens. Document data colors, image assets, syntax highlighting, neutral shadows, and selectors matching third-party markup are reviewed separately.", "",
  "## Stylesheets", "",
  ...styles.map(path => `- ${path}: ${readFileSync(resolve(root, path), "utf8").split("\n").length} lines`), "",
  "## Components", "",
  "| File | Literal palette utilities | Native controls | Inline styles | Custom CSS hooks |",
  "| --- | ---: | ---: | ---: | --- |", ...rows, "",
  "## Palette violations", "", ...(violations.length ? violations.map(value => `- ${value}`) : ["None."]), "",
].join("\n")
if (process.argv.includes("--write")) writeFileSync(resolve(root, "specs/Theme_Source_Inventory.md"), report)
console.log(`${files.length} source files, ${rows.length} TSX files, ${styles.length} stylesheets; ${violations.length} literal palette utility violations.`)
if (violations.length) { console.error(violations.join("\n")); process.exitCode = 1 }
